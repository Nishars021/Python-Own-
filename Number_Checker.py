#Integer
int_value = 15

#Check whether it is positive, negative or zero
if int_value > 0 : 
    print("Value is Positive")

if int_value < 0 : 
    print("Value is Negative")

if int_value == 0 :
    print("Value is Zero")

#Check whether it is even or odd
if int_value % 2 == 0 : 
    print("Value is Even")

if int_value % 2 != 0 : 
    print("Value is Odd")

#Check whether it is divisible by 5
if int_value % 5 == 0 :
    print("Value is divisible by 5")

else : 
    print("Value is not dividible by 5")
